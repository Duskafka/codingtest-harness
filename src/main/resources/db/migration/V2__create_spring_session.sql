-- 로그인 세션 (D22, 결정 제안서 002, data-model.md 4.3 `spring_session`, `spring_session_attributes`).
-- Spring Session JDBC 4.1.2 jar의 org/springframework/session/jdbc/schema-postgresql.sql을 그대로 옮기고
-- 테이블 이름 앞에 studybot 스키마만 붙였다 (결정 제안서 004). 앱 설정은 spring.session.jdbc.table-name=studybot.SPRING_SESSION.
-- Spring Session이 스키마를 직접 만들지 않게 spring.session.jdbc.initialize-schema=never로 둔다 (마이그레이션 원칙).

CREATE TABLE studybot.SPRING_SESSION (
	PRIMARY_ID CHAR(36) NOT NULL,
	SESSION_ID CHAR(36) NOT NULL,
	CREATION_TIME BIGINT NOT NULL,
	LAST_ACCESS_TIME BIGINT NOT NULL,
	MAX_INACTIVE_INTERVAL INT NOT NULL,
	EXPIRY_TIME BIGINT NOT NULL,
	PRINCIPAL_NAME VARCHAR(100),
	CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);

CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON studybot.SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON studybot.SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON studybot.SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE studybot.SPRING_SESSION_ATTRIBUTES (
	SESSION_PRIMARY_ID CHAR(36) NOT NULL,
	ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
	ATTRIBUTE_BYTES BYTEA NOT NULL,
	CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
	CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES studybot.SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);
